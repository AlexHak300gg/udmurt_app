insert into public.word_of_day (day, word_id) select
  (current_date + gs.day_offset)::date as day,
  w.id as word_id
from generate_series(0, 29) as gs(day_offset)
join lateral (
  select id from public.words order by id offset (gs.day_offset % 104) limit 1
) w on true
on conflict (day) do nothing;
